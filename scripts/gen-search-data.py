#!/usr/bin/env python3
"""Generates app/search-data.js: preference names (from the Preferences page renderers) and help headings
(README.md and docs/*.md) for the command palette's search box. Lazy data; the search index
loads it on the editor's idle prefetch. The in-editor Getting Started guide has a separate lazy asset.

Usage: scripts/gen-search-data.py           regenerate
       scripts/gen-search-data.py --check   exit 1 when either asset is out of date
"""
import json, os, re, sys
from asset_files import write_asset

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "search-data.js")
GUIDE = os.path.join(ROOT, "app", "getting-started-guide.js")
# Generated reference pages: their headings are tables of ids, not help topics.
SKIP = {"headless-parity.md", "reachability.md"}
PREF_RENDERERS = {"routing": "editor/prefs-routing.js"}


def prefs():
    app = os.path.join(ROOT, "app")
    with open(os.path.join(app, "editor/prefs.js"), encoding="utf-8") as source:
        src = source.read()
    pages = list(re.finditer(r'registerPage\(\{id: "(\w+)", title: "([^"]+)"', src))
    row = re.compile(r'\brow\(\w+, "([\w.]+)", "((?:[^"\\]|\\.)*)"(?:, (?:null|"((?:[^"\\]|\\.)*)"))?')
    out = []
    for i, page in enumerate(pages):
        key, title = page.groups()
        end = pages[i + 1].start() if i + 1 < len(pages) else len(src)
        body = src[page.end():end]
        if key in PREF_RENDERERS:
            with open(os.path.join(app, PREF_RENDERERS[key]), encoding="utf-8") as renderer:
                body += renderer.read()
        out.extend([m[1], m[2], m[3] or "", key, title] for m in row.finditer(body))
    return out


def slug(text):
    s = re.sub(r"[^\w\- ]", "", text.strip().lower())
    return s.replace(" ", "-")


def plain(text):
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return re.sub(r"[*_]", "", text).strip()


def headings():
    files = ["README.md"] + sorted("docs/" + f for f in os.listdir(os.path.join(ROOT, "docs")) if f.endswith(".md") and f not in SKIP)
    out = []
    for rel in files:
        fence, title = False, ""
        for line in open(os.path.join(ROOT, rel), encoding="utf-8"):
            if line.lstrip().startswith("```"):
                fence = not fence
                continue
            m = None if fence else re.match(r"(#{1,3})\s+(.+?)\s*#*\s*$", line)
            if not m:
                continue
            text = plain(m.group(2))
            if len(m.group(1)) == 1 and not title:
                title = text
            out.append([rel, text, slug(m.group(2)) if len(m.group(1)) > 1 else "", title or rel])
    return out


def render():
    body = {"prefs": prefs(), "help": headings()}
    lines = ['"use strict";',
             "// Generated by scripts/gen-search-data.py from Preferences renderers, README.md and docs/*.md; do not edit.",
             "// prefs: [key, label, help, page, page title]; help: [file, heading, anchor, document title].",
             "globalThis.AtriumSearchData = Object.freeze({",
             '  prefs: [', *["    " + json.dumps(r, ensure_ascii=False) + "," for r in body["prefs"]], "  ],",
             '  help: [', *["    " + json.dumps(r, ensure_ascii=False) + "," for r in body["help"]], "  ]",
             "});", ""]
    return "\n".join(lines)


def render_guide():
    # This guide uses headings, paragraphs, lists, and short inline spans. Keep
    # referenced document labels as text because these other docs may be absent.
    inline = re.compile(r"\x60([^\x60]*)\x60|\*\*(.+?)\*\*|\*([^*]+)\*|\[([^\]]+)\]\([^)]*\)")
    # Only complete keyboard chords are typed. Shell snippets and gestures remain text.
    shortcuts = re.compile(
        r"(?<![\w+])(?:(?:(?:Mod|Ctrl|Alt|Shift|Meta)\+)+"
        r"(?:[A-Z0-9](?!\w)|F(?:[1-9]|1[0-9]|2[0-4])(?!\w)|Space\b|[,\\])"
        r"|F(?:[1-9]|1[0-9]|2[0-4])(?!\w))"
    )
    rows = []
    with open(os.path.join(ROOT, "docs", "getting-started.md"), encoding="utf-8") as source:
        for line in source:
            text = line.strip()
            if not text or text.startswith("# "):
                continue
            heading = re.fullmatch(r"(#{2,3})\s+(.+)", text)
            item = re.fullmatch(r"(-|\d+\.)\s+(.+)", text)
            if heading:
                kind, text = "h" + str(len(heading[1]) + 1), heading[2]
            elif item:
                kind, text = item[1], item[2]
            else:
                kind = "p"
            label = inline.sub(lambda match: next(value for value in match.groups() if value is not None), text)
            spans, end = [], 0
            for match in shortcuts.finditer(label):
                if match.start() > end:
                    spans.append(label[end:match.start()])
                spans.append({"shortcut": match[0]})
                end = match.end()
            if end < len(label):
                spans.append(label[end:])
            rows.append([kind, spans])
    return "\n".join([
        '"use strict";',
        "// Generated by scripts/gen-search-data.py from docs/getting-started.md; do not edit.",
        "globalThis.AtriumGettingStartedGuide = [",
        *["  " + json.dumps(row, ensure_ascii=False) + "," for row in rows],
        "];", "",
    ])


if __name__ == "__main__":
    for path, text in ((OUT, render()), (GUIDE, render_guide())):
        if "--check" in sys.argv:
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if current != text:
                print(os.path.relpath(path, ROOT) + " is out of date; run scripts/gen-search-data.py")
                sys.exit(1)
        else:
            write_asset(path, text)
    if "--check" in sys.argv:
        print("search-data and Getting Started guide OK")
    else:
        print("wrote app/search-data.js: %d preferences, %d help headings" % (len(prefs()), len(headings())))
