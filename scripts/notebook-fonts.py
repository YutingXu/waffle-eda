#!/usr/bin/env python3
"""Build the offline font loader, or refresh its vendored subsets with --refresh (fontTools 4.59.2)."""
import base64
import io
import json
import pathlib
import urllib.parse
import urllib.request
import sys
from asset_files import write_asset

ROOT = pathlib.Path(__file__).resolve().parents[1] / "app" / "vendor" / "notebook-fonts"
PIN = "06bfe0d62a98375cb09c942fa18e68bd32cff057"
FACES = {
    "sans": ("karla", "Karla[wght].ttf", "Karla-Italic[wght].ttf"),
    "serif": ("neuton", "Neuton-Regular.ttf", "Neuton-Italic.ttf", "Neuton-Bold.ttf"),
    "mono": ("cutivemono", "CutiveMono-Regular.ttf"),
    "hand": ("kalam", "Kalam-Regular.ttf", None, "Kalam-Bold.ttf"),
}
TEXT = set(range(0x20,0x250)) | set(range(0x370,0x400)) | set(range(0x2000,0x2070)) | set(range(0x2190,0x2300)) | set(range(0x2600,0x27C0)) | {0x20ac,0xfffd}

def source(family, name):
    url = "https://raw.githubusercontent.com/google/fonts/" + PIN + "/ofl/" + family + "/" + urllib.parse.quote(name)
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read()

def face(source_bytes, family, style, weight):
    from fontTools import subset
    from fontTools.ttLib import TTFont
    from fontTools.varLib.instancer import instantiateVariableFont

    font = TTFont(io.BytesIO(source_bytes), recalcTimestamp=False)
    if "fvar" in font:
        font = instantiateVariableFont(font, {"wght":weight}, inplace=True)
    # All modified faces have new family and PostScript names, including those with reserved names.
    family_name = "Waffle Note " + family.title()
    variant = ("Bold" if weight==700 else "") + ("Italic" if style=="italic" else "") or "Regular"
    for n in font["name"].names:
        if n.nameID in (1,2,3,4,6,16,17):
            s = {1:family_name,2:variant,3:family_name+variant,4:family_name+" "+variant,6:family_name.replace(" ","")+"-"+variant,16:family_name,17:variant}[n.nameID]
            n.string = s.encode(n.getEncoding())
    options = subset.Options()
    options.hinting=False
    options.layout_features=[]
    options.name_IDs=["*"]
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=TEXT)
    sub.subset(font)
    units = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    widths = [[cp, font["hmtx"][name][0]] for cp,name in sorted(cmap.items())]
    font["head"].modified=font["head"].created
    buffer=io.BytesIO()
    font.save(buffer)
    return {"units":units,"ascent":font["hhea"].ascent,"descent":-font["hhea"].descent,"widths":widths,"bytes":base64.b64encode(buffer.getvalue()).decode("ascii")}

def refresh():
    ROOT.mkdir(parents=True,exist_ok=True)
    fonts={}
    for key,(family,regular,*extras) in FACES.items():
        license_text=source(family,"OFL.txt").decode("utf-8")
        (ROOT/(family+"-OFL.txt")).write_text("\n".join(line.rstrip() for line in license_text.splitlines())+"\n",encoding="utf-8")
        raw=source(family,regular)
        fonts[key]=face(raw,key,"normal",400)
        italic=source(family,extras[0]) if extras and extras[0] else None
        if italic: fonts[key+"-italic"]=face(italic,key,"italic",400)
        if family=="karla":
            fonts[key+"-bold"]=face(raw,key,"normal",700)
            fonts[key+"-bolditalic"]=face(italic,key,"italic",700)
        elif len(extras)>1: fonts[key+"-bold"]=face(source(family,extras[1]),key,"normal",700)
    write_asset(ROOT / "faces.json", json.dumps(fonts, separators=(",", ":")) + "\n")


def main():
    if "--refresh" in sys.argv:
        refresh()
    data = json.loads((ROOT / "faces.json").read_text(encoding="utf-8"))
    content = ('"use strict";\n// Generated by scripts/notebook-fonts.py. SIL Open Font License 1.1, see each adjacent license.\n'
               "globalThis.AtriumNotebookFontData=" + json.dumps(data, separators=(",", ":")) + ";\n")
    output = ROOT / "faces.js"
    if "--check" in sys.argv:
        if not output.is_file() or output.read_bytes() != content.encode("utf-8"):
            sys.exit("Missing or stale notebook font loader. Run python3 scripts/notebook-fonts.py.")
    else:
        write_asset(output, content)


if __name__ == "__main__":
    main()
