"""Generate the fidelity harness module manifest from the native resolver."""
import json
from pathlib import Path
import sys

from asset_files import write_asset

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "tests/e2e/modules.cjs"
CORE = ("core", "parts", "import-formats", "import-rules", "erc", "connectivity", "stackup", "pcb-appearance",
        "board-shape", "viastack", "via-stubs", "rule-sets", "dfa", "drc", "polygon-pour", "si", "ipc2152",
        "fab-outputs", "bom", "print", "altium-export", "ipc2581", "step-export", "format-2-model",
        "format-2-closure", "translator-precision", "folder-project-mcp", "format-2-models")


def prepare_modules(check=False):
    sys.path.insert(0, str(ROOT / "mcp"))
    from board_runner import resolve, translator_modules, translator_table

    table = translator_table()
    names = CORE + translator_modules([entry for entry in table if entry["import"]], "import") \
        + translator_modules([entry for entry in table if entry["export"]], "export")
    rows = ",\n".join("  " + json.dumps([name, path.relative_to(ROOT).as_posix()]) for name, path in resolve(names))
    content = ('"use strict";\n'
               "// Generated by scripts/prepare-assets.py from mcp/board_runner.py.\n"
               "const MODULES = [\n" + rows + "\n];\n"
               "function load(root) {\n"
               "  const path = require(\"node:path\");\n"
               "  if (!globalThis.performance) globalThis.performance = {now:() => Date.now()};\n"
               "  for (const [name, file] of MODULES) {\n"
               "    const full = path.join(root, file);\n"
               "    if (name === \"cfb\") globalThis.CFB = require(full);\n"
               "    else require(full);\n"
               "  }\n"
               "}\n"
               "module.exports = {MODULES, load};\n")
    if check:
        if not TARGET.is_file() or TARGET.read_bytes() != content.encode("utf-8"):
            sys.exit("tests/e2e/modules.cjs is missing or stale. Run python3 scripts/prepare-assets.py.")
    else:
        write_asset(TARGET, content)
