#!/usr/bin/env python3
"""Write the loaders for the fab capability presets (app/fab-presets/<vendor>.json -> <vendor>.js).

The JSON files are the source of truth (values with their source URL and retrieval date). The app
loads scripts, not JSON, so it works from file:// without fetch; each loader is the JSON wrapped in
one AtriumFabPresets.define() call.

  scripts/fab-presets.py           regenerate every loader
  scripts/fab-presets.py --check   exit 1 when a loader is missing or out of date, or a JSON file is invalid
"""
import json
from pathlib import Path
import sys
from asset_files import write_asset

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "app" / "fab-presets"
GLOBAL = {"jlcpcb": "AtriumFabPresetsJLCPCB"}


def loader(path):
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("format") != "atrium-fab-preset" or not isinstance(data.get("version"), int):
        raise SystemExit("%s: not an atrium-fab-preset file" % path.name)
    name = GLOBAL.get(path.stem) or ("AtriumFabPresets" + "".join(c for c in data["vendor"] if c.isalnum()))
    body = json.dumps(data, ensure_ascii=False, indent=1)
    return ('"use strict";\n// Generated by scripts/fab-presets.py from ' + path.name + ": edit the JSON and run the script.\n"
            "globalThis." + name + " = globalThis.AtriumFabPresets.define(" + body + ");\n")


def main():
    check = "--check" in sys.argv
    ok = True
    for path in sorted(DIR.glob("*.json")):
        text, out = loader(path), path.with_suffix(".js")
        if check:
            if not out.exists() or out.read_text(encoding="utf-8") != text:
                print("out of date: " + str(out.relative_to(ROOT)))
                ok = False
        elif not out.exists() or out.read_text(encoding="utf-8") != text:
            write_asset(out, text)
            print("wrote " + str(out.relative_to(ROOT)))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
