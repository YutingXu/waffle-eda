#!/usr/bin/env python3
"""Package the private PDF.js worker for desktop file origins."""
import argparse
import hashlib
import json
from pathlib import Path
import re

from asset_files import write_asset

APP = Path(__file__).resolve().parents[1] / "app"
SOURCES = ("vendor/pdfjs/pdf.min.mjs","vendor/pdfjs/pdf.worker.min.mjs","notebook/datasheet-document.mjs","workers/datasheet-worker.mjs")

PINNED = {
    "vendor/pdfjs/LICENSE": "0d542e0c8804e39aa7f37eb00da5a762149dc682d7829451287e11b938e94594",
    "vendor/pdfjs/pdf.min.mjs": "3a88402882cfa3e7e72c2c9b5149f52f0f88baf1c5b62aa11a41abdbc2072440",
    "vendor/pdfjs/pdf.worker.min.mjs": "1e64c8240e54735ec5913b37acd5134747799cb8c6bb3777c70adbc01232d2aa",
}

def build():
    for file, expected in PINNED.items():
        if hashlib.sha256((APP / file).read_bytes()).hexdigest() != expected:
            raise ValueError(f"PDF.js 6.5.438 vendor bytes differ from the pinned release: {file}")
    def vendored(name):
        text = (APP / name).read_text(encoding="utf-8")
        trailer = re.search(r"export\{([^}]+)\};\s*$",text)
        if not trailer:
            raise ValueError(f"Unrecognized PDF.js module export list: {name}")
        symbols = {}
        for value in trailer[1].split(","):
            names = value.strip().split(" as ")
            symbols[names[-1]] = names[0]
        # The classic file-origin worker has the same URL through its location.
        return text[:trailer.start()].replace("import.meta.url","globalThis.location.href"),symbols

    def internal(name):
        text = (APP / name).read_text(encoding="utf-8")
        text = re.sub(r'^import [^\n]+;\n',"",text,flags=re.M)
        return re.sub(r"^export (?=const |(?:async )?function )","",text,flags=re.M)

    display, symbols = vendored(SOURCES[0])
    parser,_ = vendored(SOURCES[1])
    names = ("AnnotationMode","getDocument")
    # Opaque file origins reject module workers. Keep the pinned vendor code
    # in separate scopes inside one classic blob worker.
    worker = ('"use strict";\nconst {'+",".join(names)+"}=(()=>{\n"+display+
              "\nreturn {"+",".join(name+":"+symbols[name] for name in names)+"};\n})();\n"+
              "(()=>{\n"+parser+"\n})();\n"+
              internal(SOURCES[2])+"\n"+internal(SOURCES[3]))
    return ("// Generated by scripts/bundle-datasheet.py from Mozilla PDF.js 6.5.438 (Apache-2.0).\n"+
            "// Waffle wrapped the display and parser module boundaries for offline file-origin execution.\n"+
            "// Source modules and the original license are in vendor/pdfjs/.\n"+
            "globalThis.AtriumDatasheetWorkerSource = (() => {\n  const worker = "+
            json.dumps(worker,ensure_ascii=True)+";\n"+
            """  return Object.freeze({create() {
    const url = URL.createObjectURL(new Blob([worker],{type:"text/javascript"}));
    return {url,type:"classic",close:()=>URL.revokeObjectURL(url)};
  }});
})();
""")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true")
    args = parser.parse_args()
    path = APP / "datasheet-worker-source.js"
    content = build()
    if args.check:
        if not path.is_file() or path.read_bytes()!=content.encode("utf-8"):
            parser.exit(1,"datasheet-worker-source.js is stale. Regenerate the package assets.\n")
    else:
        write_asset(path,content)


if __name__ == "__main__":
    main()
