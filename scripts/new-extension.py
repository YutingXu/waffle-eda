#!/usr/bin/env python3
"""Scaffold a new Waffle extension from extensions/template/.

    python3 scripts/new-extension.py yourname.hello-nets            # -> extensions/examples/hello-nets/
    python3 scripts/new-extension.py yourname.hello-nets --out ~/src/hello-nets
    python3 scripts/new-extension.py --bundle                       # regenerate app/extension-template.js
    python3 scripts/new-extension.py --bundle --check               # CI: fail if it is stale

The scaffold has waffle-extension.json (least privilege: read:project, ui:command, ui:panel),
main.js, test.cjs (runs in the sandbox harness, extensions/examples/harness.cjs) and README.md.
The in-app Tools > Extensions > New Extension... builds the same files from
app/extension-template.js, which --bundle generates from extensions/template/.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path
from asset_files import write_asset

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "extensions" / "template"
BUNDLE = ROOT / "app" / "extension-template.js"
FILES = ["waffle-extension.json", "main.js", "test.cjs", "README.md"]
# Same rule as validateManifest in app/extensions.js.
ID = re.compile(r"^[a-z0-9][a-z0-9_-]*(\.[a-z0-9][a-z0-9_-]*)+$", re.I)


def names(ext_id):
    """id -> placeholder values. Mirrored by fill() in app/extension-dev.js."""
    if not ID.match(ext_id) or len(ext_id) > 80:
        raise SystemExit(f"{ext_id!r} is not a valid id: use publisher.name (letters, digits, - and _, dots between parts)")
    publisher, last = ext_id.split(".")[0], ext_id.split(".")[-1]
    words = [w for w in re.split(r"[-_]+", last) if w]
    prefix = words[0].lower() + "".join(w[:1].upper() + w[1:].lower() for w in words[1:])
    if prefix[:1].isdigit():
        prefix = "x" + prefix
    return {"__ID__": ext_id, "__NAME__": " ".join(w[:1].upper() + w[1:] for w in words),
            "__PUBLISHER__": publisher, "__PREFIX__": prefix}


def fill(text, values):
    for k, v in values.items():
        text = text.replace(k, v)
    return text


def scaffold(ext_id, out):
    values = names(ext_id)
    out = Path(out).expanduser().resolve()
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f"{out} already exists and is not empty")
    out.mkdir(parents=True, exist_ok=True)
    values["__WAFFLE__"] = os.path.relpath(ROOT, out)
    for name in FILES:
        (out / name).write_text(fill((TEMPLATE / name).read_text(encoding="utf-8"), values), encoding="utf-8")
    json.loads((out / "waffle-extension.json").read_text(encoding="utf-8"))  # the template must stay valid JSON
    try:
        shown = out.relative_to(Path.cwd())
    except ValueError:
        shown = out
    print(f"Created {shown}/ ({', '.join(FILES)})")
    print("Next:")
    print(f"  test:     /System/Library/Frameworks/JavaScriptCore.framework/Versions/Current/Helpers/jsc {ROOT}/tests/jsc-shim.js -- {out}/test.cjs")
    print("  develop:  Preferences > Extension Development > Developer mode, then Tools > Extensions... > Load unpacked...")
    print("  API:      docs/extension-api.md")


def bundle_text():
    files = {name: (TEMPLATE / name).read_text(encoding="utf-8") for name in FILES}
    body = json.dumps(files, indent=2, ensure_ascii=False)
    return ('"use strict";\n'
            "// GENERATED by scripts/new-extension.py --bundle from extensions/template/. Do not edit.\n"
            "// The New Extension... scaffold (app/extension-host/extension-dev.js): placeholder files that fill() completes.\n"
            "globalThis.AtriumExtensionTemplate = Object.freeze({files: Object.freeze(" + body + ")});\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("id", nargs="?", help="publisher.name, e.g. yourname.hello-nets")
    ap.add_argument("--out", help="target folder (default extensions/examples/<name>)")
    ap.add_argument("--bundle", action="store_true", help="write app/extension-template.js from extensions/template/")
    ap.add_argument("--check", action="store_true", help="with --bundle: fail if app/extension-template.js is stale")
    a = ap.parse_args()
    if a.bundle:
        text = bundle_text()
        current = BUNDLE.read_text(encoding="utf-8") if BUNDLE.exists() else ""
        if a.check:
            if current != text:
                sys.exit("app/extension-template.js is stale: run python3 scripts/new-extension.py --bundle")
            print("app/extension-template.js is current")
            return
        if current != text:
            write_asset(BUNDLE, text)
        print("wrote app/extension-template.js" if current != text else "app/extension-template.js is current")
        return
    if not a.id:
        ap.error("give an extension id, e.g. yourname.hello-nets (or --bundle)")
    scaffold(a.id, a.out or ROOT / "extensions" / "examples" / a.id.split(".")[-1])


if __name__ == "__main__":
    main()
