#!/usr/bin/env python3
"""Builds the two ways to set up a Waffle collaboration server (deploy/collab-server/README.md) from
deploy/collab-server/waffle-collab (the setup and status helper) and collab/relay/waffle_relay.py:

  deploy/collab-server/waffle-setup.sh    the complete installer (helper and relay), pasted into the
                                          instance's SSH session: sudo bash waffle-setup.sh DOMAIN [EMAIL]
  deploy/collab-server/launch-script.sh   a Lightsail launch script (cloud-init user data) with the
                                          helper only: it prepares the server at first boot (packages,
                                          TLS, TURN, firewall); waffle-setup.sh then adds the relay

The files travel inside as an xz-compressed, base85-encoded tar archive. Comments, docstrings, blank
lines and most indentation are left out of those copies (the repository keeps the commented sources);
the code is otherwise unchanged and the relay copy is compiled here to make sure.

    python3 scripts/gen-collab-launch.py           # rewrite both scripts
    python3 scripts/gen-collab-launch.py --check   # fail when either is out of date (CI)

Lightsail refused a 16,209-byte launch script; this keeps launch-script.sh at most LAUNCH_LIMIT bytes, leaving
room for the edited DOMAIN and e-mail lines.
"""
import base64
import hashlib
import io
import lzma
from pathlib import Path
from asset_files import write_asset
import re
import sys
import tarfile
import textwrap
import tokenize

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / "deploy" / "collab-server"
HELPER = KIT / "waffle-collab"
RELAY = ROOT / "collab" / "relay" / "waffle_relay.py"
LAUNCH_LIMIT = 13000

# A paste through a browser terminal can add carriage returns and spaces at line ends (or indent
# lines). The second line notices and re-runs a cleaned copy; it ends in "#" so that a trailing CR
# on it is a comment. The payload decoder ignores all whitespace and checks the payload's SHA-256.
PREAMBLE = """#!/bin/bash
if grep -qE '^[[:space:]]|[[:space:]]$' "$0" 2>/dev/null; then c=$(mktemp) && sed 's/^[[:space:]]*//;s/[[:space:]]*$//' "$0" > "$c" && exec bash "$c" "$@"; fi #
# Generated by scripts/gen-collab-launch.py from deploy/collab-server/waffle-collab and
# collab/relay/waffle_relay.py: edit those, then regenerate. See deploy/collab-server/README.md.
"""
# WAFFLE_UNPACK_ROOT=dir: unpack there and stop (tests/project/collab-server-kit.py).
UNPACK = """set -o pipefail
UNPACK_ROOT=${WAFFLE_UNPACK_ROOT:-/}
python3 -c '
import base64, hashlib, sys
def fail(why): sys.exit("The paste was altered (" + why + "). Copy the file again as plain text and paste it whole.")
try: data = base64.b85decode("".join(sys.stdin.read().split()))
except ValueError as e: fail(str(e))
got = hashlib.sha256(data).hexdigest()
if got != sys.argv[1]: fail("expected sha256 " + sys.argv[1] + ", got " + got)
sys.stdout.buffer.write(data)
' %(sha)s <<'FILES' | tar -xJ --no-same-owner -C "$UNPACK_ROOT" || { echo "Could not unpack the files (see above)."; exit 1; }
"""
LAUNCH_HEAD = PREAMBLE + """# AWS Lightsail launch script for Ubuntu 24.04 LTS: prepares the server at first boot. Then add the
# relay from the instance's SSH session with waffle-setup.sh. Edit the two values below first.
DOMAIN="collab.example.org"      # the server's DNS name: an A record pointing at the instance's static IP
ACME_EMAIL=""                    # optional: an e-mail for Let's Encrypt notices
L=/var/log/waffle-collab-setup.log   # root only; nothing secret is written to it
[ -n "${WAFFLE_UNPACK_ROOT:-}" ] || { (umask 077; : >>$L); chmod 600 $L; exec >>$L 2>&1; }
echo "== Waffle collaboration server (launch script) $(date -u +%FT%TZ)"
""" + UNPACK
LAUNCH_TAIL = """FILES
[ -z "${WAFFLE_UNPACK_ROOT:-}" ] || exit 0
chmod 0755 /usr/local/sbin/waffle-collab
if [ -r /etc/waffle-collab/config ] || [ -r /etc/atrium-collab/config ]; then set --; else set -- "$DOMAIN" "$ACME_EMAIL"; fi
exec /usr/local/sbin/waffle-collab setup "$@"
"""
SETUP_HEAD = PREAMBLE + """# Installs or updates a Waffle collaboration server on Ubuntu 24.04 LTS: Caddy (TLS), the relay,
# coturn (TURN), firewall and automatic updates. Idempotent.
#   sudo bash waffle-setup.sh collab.example.org [you@example.org]
#   sudo bash waffle-setup.sh          (after the launch script: keeps its domain)
set -u
[ -n "${WAFFLE_UNPACK_ROOT:-}" ] || [ "$(id -u)" = 0 ] || { echo "run it with sudo"; exit 1; }
""" + UNPACK
SETUP_TAIL = """FILES
[ -z "${WAFFLE_UNPACK_ROOT:-}" ] || exit 0
chmod 0755 /usr/local/sbin/waffle-collab
chmod 0644 /opt/waffle-collab/waffle_relay.py
L=/var/log/waffle-collab-setup.log; (umask 077; : >>$L); chmod 600 $L
/usr/local/sbin/waffle-collab setup "$@" | tee -a $L
"""


def compact_sh(text):
    """Comments, blank lines and leading indentation out (shebang kept). Heredoc bodies here are
    config files and units, where neither matters."""
    out = []
    for i, line in enumerate(text.split("\n")):
        if i and (re.match(r"\s*#", line) or not line.strip()):
            continue
        out.append(line if not i else line.lstrip())
    return "\n".join(out) + "\n"


def compact_py(text):
    """Comments, docstrings and blank lines out, four-space indentation down to one, by token
    positions; multi-line string literals are left exactly as they are."""
    toks = list(tokenize.generate_tokens(io.StringIO(text).readline))
    drop, cut, literal = set(), {}, set()
    prev = None
    for i, t in enumerate(toks):
        if t.type == tokenize.COMMENT:
            cut[t.start[0]] = min(cut.get(t.start[0], 1 << 30), t.start[1])
        elif t.type == tokenize.STRING:
            if t.end[0] > t.start[0]:
                literal.update(range(t.start[0] + 1, t.end[0] + 1))
            statement = prev is None or prev.type in (tokenize.INDENT, tokenize.DEDENT, tokenize.NEWLINE)
            if statement and i + 1 < len(toks) and toks[i + 1].type == tokenize.NEWLINE:
                drop.update(range(t.start[0], t.end[0] + 1))
        if t.type not in (tokenize.NL, tokenize.COMMENT):
            prev = t
    out = []
    for n, line in enumerate(text.split("\n"), 1):
        if n in drop and n > 1:
            continue
        if n in cut:
            line = line[:cut[n]].rstrip()
        if not line.strip() and n not in literal:
            continue
        if n not in literal:
            k = len(line) - len(line.lstrip(" "))
            line = " " * (k // 4 + k % 4) + line[k:]
        out.append(line)
    result = "\n".join(out) + "\n"
    compile(result, str(RELAY), "exec")
    return result


def payload(with_relay):
    buf = io.BytesIO()
    files = [(HELPER, "usr/local/sbin/waffle-collab", 0o755, compact_sh)]
    if with_relay:
        files.append((RELAY, "opt/waffle-collab/waffle_relay.py", 0o644, compact_py))
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.GNU_FORMAT) as tar:
        for source, target, mode, compact in files:
            data = compact(source.read_text()).encode()
            info = tarfile.TarInfo(target)
            info.size, info.mode, info.mtime, info.uid, info.gid, info.uname, info.gname = len(data), mode, 0, 0, 0, "root", "root"
            tar.addfile(info, io.BytesIO(data))
    packed = lzma.compress(buf.getvalue(), format=lzma.FORMAT_XZ, preset=9 | lzma.PRESET_EXTREME)
    return "\n".join(textwrap.wrap(base64.b85encode(packed).decode("ascii"), 76)) + "\n", hashlib.sha256(packed).hexdigest()


def script(head, with_relay, tail):
    data, sha = payload(with_relay)
    return head.replace("%(sha)s", sha) + data + tail


def build():
    # No line of a generated script may start or end with whitespace: the first lines would take that
    # for a mangled paste and re-run a cleaned copy.
    return {KIT / "launch-script.sh": script(LAUNCH_HEAD, False, LAUNCH_TAIL),
            KIT / "waffle-setup.sh": script(SETUP_HEAD, True, SETUP_TAIL)}


def main(argv):
    outputs = build()
    for path, text in outputs.items():
        bad = [n for n, line in enumerate(text.split("\n"), 1) if line != line.strip()]
        if bad:
            raise SystemExit("gen-collab-launch: %s lines %s start or end with whitespace" % (path.name, bad[:5]))
    launch = len(outputs[KIT / "launch-script.sh"].encode())
    if launch > LAUNCH_LIMIT:
        raise SystemExit("gen-collab-launch: launch-script.sh is %d bytes, over the %d byte limit" % (launch, LAUNCH_LIMIT))
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_bytes() != text.encode("utf-8")]
    sizes = ", ".join("%s %d bytes" % (p.name, len(t.encode())) for p, t in outputs.items())
    if "--check" in argv:
        if stale:
            print("gen-collab-launch --check: %s out of date; run python3 scripts/gen-collab-launch.py" % ", ".join(p.name for p in stale))
            return 1
        print("gen-collab-launch --check: OK (%s)" % sizes)
        return 0
    for path, text in outputs.items():
        write_asset(path, text)
        path.chmod(0o755)
    print("wrote " + sizes)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
