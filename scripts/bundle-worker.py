#!/usr/bin/env python3
"""Build the classic-script registry and offline translator worker. --check verifies both."""
import argparse
import json
import re
from pathlib import Path
import sys
from asset_files import write_asset

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "app"
sys.path.insert(0, str(ROOT / "mcp"))
from board_runner import resolve

# The headless runner supplies the dependency order for the same serializers and readers.
# These optional accelerators and PDF display assets have JS/data-only paths in a worker.
OMIT = {"engine-core.js", "vendor/dejavu-sans.js", "formats/pdf.js", "core/path-record.js"}
FRAMEWORK = ("project/obsolete-project.js", "translator-table.js", "formats/translator-registry.js", "translator-worker-modules.js", "formats/translators.js")
ADAPTERS = ("formats/translator-provenance.js", "formats/translator-adapters.js", "formats/translator-exports.js", "formats/translator-manufacturing.js")
NATIVE_OPEN = (".waffle", ".wpcb", ".wsch", ".wlib", ".wdraw", ".wpanel")
FOLDER_WORKER = (
    "core/base64.js", "core/sha256.js", "project/source-file.js", "core/uuid-v7.js", "pcb/pour-marker.js", "formats/format-2-codec.js", "formats/format-2-upgrades.js", "formats/format-2-units.js", "formats/format-2-values.js", "project/link-record.js", "formats/format-2-model.js",
    "project/folder-project-engine.js", "formats/format-2-closure.js", "formats/import-sidecars.js", "formats/format-2-models.js", "checks/design-query-record.js", "notebook/datasheet-record.js",
    "notebook/notebook-image-format.js", "notebook/notebook.js", "notebook/table-data.js", "notebook/table-format.js",
    "project/revisions.js", "formats/translator-provenance.js", "core/zip.js", "formats/sexpr.js", "vendor/zipjs-deflate.js",
)


CALCULATIONS = ("notebook/calculation-intent.js", "notebook/calculation-core.js", "notebook/preferred-values.js", "notebook/calculation-helpers.js", "notebook/calculation-graph.js", "workers/calculation-worker.js")

def encoded(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def build():
    table = json.loads((APP / "translators.json").read_text(encoding="utf-8"))
    roots = {"source-copy", "altium-io", "import-formats", "frame-conversion", "notebook-output", "notebook", "calculations", "math", "sheet-widgets", "table-visual"}
    for row in table:
        for direction in ("import", "export"):
            if row[direction]:
                roots.update(row["modules"][direction])
    dependencies = {}
    for root in sorted(roots):
        files = (path.relative_to(APP).as_posix() for _, path in resolve([root]) if APP in path.parents)
        dependencies[root] = [file for file in files if file not in OMIT]
    generated = {
        "translator-table.js": "// Generated from translators.json by scripts/bundle-worker.py.\n"
                               "globalThis.AtriumTranslatorTable = " + encoded(table) + ";\n",
        "translator-worker-modules.js": "// Generated from translator roots and their headless module dependencies.\n"
                                       "globalThis.AtriumTranslatorWorkerModules = " + encoded(dependencies) + ";\n",
    }
    names = dict.fromkeys([*FRAMEWORK, *(file for files in dependencies.values() for file in files), *ADAPTERS])
    # Embedded functions permit lazy execution with the desktop CSP (no eval, network or
    # dynamically generated code). A static worker imports each original file on demand.
    def packaged(scripts):
        functions = []
        for name in scripts:
            source = generated[name] if name in generated else (APP / name).read_text(encoding="utf-8")
            if name == "vendor/cfb.min.js":
                source += "\nglobalThis.CFB = CFB;\n"  # The classic vendor script declares a global var.
            functions.append(encoded(name) + ": function () {\n" + source + "\n}")
        return ",\n".join(functions)

    bootstrap = "globalThis.AtriumEmbeddedTranslatorScripts = {\n" + packaged(names) + "\n};\n"
    bootstrap += (APP / "workers/import-worker.js").read_text(encoding="utf-8")
    generated["worker-source.js"] = ("// Generated by scripts/bundle-worker.py. Edit the individual translator sources.\n"
                                     "globalThis.AtriumImportWorkerSource = " + json.dumps(bootstrap, ensure_ascii=True) + ";\n")
    # Only a conversion that adopts or certifies copper needs this source on an opaque file origin.
    # Opening and editing a native folder can continue to start the smaller project worker.
    copper_scripts = ["translator-worker-modules.js", *(name for name in dependencies["polygon-pour"] if name not in FOLDER_WORKER)]
    copper_worker = '"use strict";\nglobalThis.AtriumFolderCopperScripts = {\n' + packaged(copper_scripts) + "\n};\n"
    generated["folder-copper-worker-source.js"] = (
        "// Generated by scripts/bundle-worker.py. Edit the individual folder worker sources.\n"
        "globalThis.AtriumFolderCopperWorkerSource = " + json.dumps(copper_worker, ensure_ascii=True) + ";\n")
    folder_worker = ('"use strict";\nconst packaged = Object.assign({\n' + packaged(FOLDER_WORKER) + "\n}, globalThis.AtriumFolderCopperScripts);\n"
                     "const loaded = new Set();\n"
                     "globalThis.importScripts = (...files) => {\n"
                     "  for (const supplied of files) {\n"
                     "    const file = supplied.startsWith('../') ? supplied.slice(3) : supplied;\n"
                     "    if (loaded.has(file)) continue;\n"
                     "    if (!Object.hasOwn(packaged,file)) throw Error('Unknown folder worker module: ' + file);\n"
                     "    packaged[file](); loaded.add(file);\n"
                     "  }\n"
                     "};\n" + (APP / "workers/folder-project-worker.js").read_text(encoding="utf-8"))
    generated["folder-project-worker-source.js"] = (
        "// Generated by scripts/bundle-worker.py. Edit the individual folder worker sources.\n"
        "globalThis.AtriumFolderProjectWorkerSource = " + json.dumps(folder_worker, ensure_ascii=True) + ";\n")
    # The file chooser requires an accept filter synchronously inside a user click, before
    # any lazy scripts can run. Keep its HTML attribute a checked projection of the registry.
    html = (APP / "index.html").read_text(encoding="utf-8")
    accepted = dict.fromkeys([*NATIVE_OPEN, *(ext for row in table if row["import"] for ext in row["extensions"])])
    accepted[".zip"] = None  # A project archive uses its verified extraction flow.
    accepts = ",".join(accepted)
    html, changes = re.subn(r'(<input\b(?=[^>]*\bid="file-input")[^>]*?\baccept=")[^"]*(")', r'\g<1>' + accepts + r'\2', html)
    if changes != 1:
        raise ValueError("Expected one file-input accept attribute in app/index.html")
    generated["index.html"] = html
    return generated


def build_calculation():
    source = "\n;\n".join((APP / name).read_text(encoding="utf-8") for name in CALCULATIONS)
    header = "// Generated by scripts/bundle-worker.py. Edit the individual calculation sources.\n"
    return {"calculation-worker-source.js": header + "globalThis.AtriumCalculationWorkerSource = "
            + json.dumps(source, ensure_ascii=True) + ";\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--only", choices=("import", "calculation"))
    parser.add_argument("--assets", action="store_true", help="regenerate assets and validate the source HTML")
    args = parser.parse_args()
    generated = build() if args.only != "calculation" else {}
    if args.only != "import":
        generated.update(build_calculation())
    for name, content in generated.items():
        path = APP / name
        if args.check or (args.assets and name == "index.html"):
            expected = content.encode("utf-8")
            if not path.is_file() or (path.read_text(encoding="utf-8").encode("utf-8") if name == "index.html"
                                      else path.read_bytes()) != expected:
                parser.exit(1, name + " is stale. Run python3 scripts/bundle-worker.py.\n")
        else:
            write_asset(path, content)


if __name__ == "__main__":
    main()
