#!/usr/bin/env python3
"""Builds the Rust/WebAssembly kernels (engine/) into their loader and two local payload scripts.

    python3 scripts/build-engine.py            # cargo test, cargo build, regenerate the three JS files
    python3 scripts/build-engine.py --check    # the same build; fails unless all three files match
    python3 scripts/build-engine.py --no-test  # skip cargo test
    python3 scripts/build-engine.py --print-wasm PATH   # also copy the built modules to PATH (MVP)
                                                        # and PATH with .simd.wasm (simd128)

The app has no build step at run time: app/engine-core.js is generated by the build and loaded
lazily (app/lazy.js). It combines engine/loader.js and engine/bridge.js, selecting one local payload script: an MVP
module (-C target-cpu=mvp: every WKWebView, WebKitGTK and WebView2) and a simd128 one (the same
plus +simd128: WebAssembly SIMD in the pour core's hot loops, engine/src/pour.rs `lanes`, with
answers identical bit for bit); the bridge loads the SIMD one where WebAssembly.validate accepts
a SIMD probe, else the MVP one. The build is
reproducible: the toolchain is pinned (engine/rust-toolchain.toml), there are no
dependencies (Cargo.lock, --locked --offline), build paths are remapped, and --check compares
a fresh build with all three output files byte for byte. CI runs --check (scripts/ci-local.sh rust,
scripts/ci-linux.sh rust).

Needs cargo with the wasm32-unknown-unknown target: rustup reads engine/rust-toolchain.toml.
Set CARGO=/path/to/cargo to use a specific cargo.
"""
import argparse
import base64
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from asset_files import write_asset

ROOT = Path(__file__).resolve().parent.parent
ENGINE = ROOT / "engine"
APP = ROOT / "app"
TARGET = "wasm32-unknown-unknown"
OUTPUTS = ("engine-core.js", "engine-mvp.js", "engine-simd128.js")
STAMP = ROOT / "dist" / ".engine-assets.sha256"


def toolchain():
    text = (ENGINE / "rust-toolchain.toml").read_text(encoding="utf-8")
    m = re.search(r'^channel\s*=\s*"([^"]+)"', text, re.M)
    if not m:
        sys.exit("engine/rust-toolchain.toml has no channel")
    return m.group(1)


def run(cmd, env, cwd=ENGINE, capture=False):
    r = subprocess.run(cmd, cwd=cwd, env=env, text=True, stdout=subprocess.PIPE if capture else None)
    if r.returncode != 0:
        sys.exit("build-engine: %s failed (exit %d)" % (" ".join(map(str, cmd[:3])), r.returncode))
    return r.stdout


# Each module: (name, extra codegen flags). Separate target directories keep both reproducible.
MODULES = (("mvp", []), ("simd128", ["-C", "target-feature=+simd128"]))


def build(env, cargo, target_dir, extra):
    # Paths that would otherwise end up in panic messages: the checkout and the toolchain homes.
    remaps = [(ENGINE, "/waffle/engine")]
    for name, alias in (("CARGO_HOME", "/cargo"), ("RUSTUP_HOME", "/rustup")):
        home = env.get(name) or str(Path.home() / ("." + name.split("_")[0].lower()))
        remaps.append((Path(home), alias))
    flags = ["-C", "target-cpu=mvp"] + extra  # MVP WebAssembly (plus simd128 for the SIMD module)
    for src, alias in remaps:
        flags.append("--remap-path-prefix=%s=%s" % (Path(src).resolve(), alias))
    env = dict(env, CARGO_ENCODED_RUSTFLAGS="\x1f".join(flags), SOURCE_DATE_EPOCH="0")
    env.pop("RUSTFLAGS", None)
    run([cargo, "build", "--offline", "--locked", "--release", "--target", TARGET, "--target-dir", target_dir], env)
    return (Path(target_dir) / TARGET / "release" / "atrium_engine.wasm").read_bytes()


def generate(wasm, simd, rustc):
    header = '"use strict";\n// Generated by scripts/build-engine.py from the pinned Rust build and engine/ JS sources.\n'
    bridge = (ENGINE / "bridge.js").read_text(encoding="utf-8").strip()
    loader = (ENGINE / "loader.js").read_text(encoding="utf-8").strip()
    files = {"engine-core.js": header + "globalThis.AtriumEngine = " + loader + "(\n" + bridge + ");\n"}
    for name, data in (("mvp", wasm), ("simd128", simd)):
        files["engine-" + name + ".js"] = (
            header + "// %s, %s, %s; %d bytes, SHA-256 %s.\n" % (rustc, TARGET, name, len(data), hashlib.sha256(data).hexdigest()) +
            '(function (data) {\n  if (typeof module === "object" && module.exports) module.exports = data;\n' +
            '  else globalThis.AtriumEngine.install("%s", data);\n})("%s");\n' % (name, base64.b64encode(data).decode("ascii")))
    return files


def digests(data):
    return "".join(hashlib.sha256(value).hexdigest() + "\n" for value in data)


def source_signature():
    inputs = [Path(__file__), *sorted(ENGINE.glob("*.js")), *sorted(ENGINE.glob("*.toml")),
              ENGINE / "Cargo.lock", *sorted((ENGINE / "src").rglob("*.rs"))]
    return digests(path.read_bytes().replace(b"\r\n", b"\n") for path in inputs)


def current_build_signature(source):
    try:
        return source + digests((APP / name).read_bytes() for name in OUTPUTS)
    except FileNotFoundError:
        return None


def find_cargo(env):
    if env.get("CARGO"):
        return env["CARGO"]
    executable = "cargo.exe" if os.name == "nt" else "cargo"
    cache = Path.home() / ".cache" / "atrium-rust"
    cached = cache / "cargo" / "bin" / executable
    if cached.is_file() and not (env.get("CARGO_HOME") or env.get("RUSTUP_HOME")):
        env["CARGO_HOME"] = str(cache / "cargo")
        env["RUSTUP_HOME"] = str(cache / "rustup")
        return str(cached)
    cargo = shutil.which("cargo")
    if cargo:
        return cargo
    local = Path(env.get("CARGO_HOME") or Path.home() / ".cargo") / "bin" / executable
    if local.is_file():
        return str(local)
    sys.exit("build-engine: cargo not found. Install Rust with rustup (engine/rust-toolchain.toml pins "
             + toolchain() + " and the wasm32-unknown-unknown target).")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail unless the generated engine assets match a fresh build")
    mode.add_argument("--ensure", action="store_true", help="reuse a current build or rebuild missing/stale files")
    mode.add_argument("--check-assets", action="store_true", help="verify the source and output byte hashes")
    ap.add_argument("--no-test", action="store_true", help="skip cargo test")
    ap.add_argument("--print-wasm", metavar="PATH", help="also write the MVP .wasm here and the simd128 one beside it (.simd.wasm)")
    args = ap.parse_args()

    source = source_signature()
    signature = current_build_signature(source)
    current = signature is not None and STAMP.is_file() and STAMP.read_text(encoding="ascii") == signature
    if args.check_assets:
        if not current:
            sys.exit("Missing or stale engine assets. Run python3 scripts/prepare-assets.py.")
        return
    if args.ensure and current and not args.print_wasm:
        return
    env = dict(os.environ)
    cargo = find_cargo(env)
    rustc_exe = "rustc.exe" if os.name == "nt" else "rustc"
    version = run([env.get("RUSTC") or str(Path(cargo).with_name(rustc_exe)), "--version"], env, capture=True).strip()
    want = toolchain()
    if not version.startswith("rustc %s " % want):
        sys.exit("build-engine: %s, but engine/rust-toolchain.toml pins %s" % (version, want))
    rustc = "rustc " + want

    with tempfile.TemporaryDirectory(prefix="waffle-engine-") as tmp:
        if not args.no_test:
            run([cargo, "test", "--offline", "--locked", "--target-dir", tmp + "/host"], env)
        wasm, simd = (build(env, cargo, tmp + "/wasm-" + name, extra) for name, extra in MODULES)
    if args.print_wasm:
        Path(args.print_wasm).write_bytes(wasm)
        Path(args.print_wasm).with_suffix(".simd.wasm").write_bytes(simd)
    outputs = {name: text.encode("utf-8") for name, text in generate(wasm, simd, rustc).items()}
    if source_signature() != source:
        sys.exit("Engine sources changed during the build. Run the command again.")
    for filename, data in outputs.items():
        dest = APP / filename
        if args.check:
            if not dest.exists() or dest.read_bytes() != data:
                sys.exit("build-engine --check: app/%s differs from a fresh build" % filename)
        else:
            write_asset(dest, data)
        print("build-engine: %s app/%s (%d bytes)" % ("verified" if args.check else "wrote", filename, len(data)))
    if not args.check:
        write_asset(STAMP, source + digests(outputs[name] for name in OUTPUTS))


if __name__ == "__main__":
    main()
