#!/usr/bin/env python3
"""Generate the offline editor's lazy Butter command catalogue."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "mcp"))
from butter_commands import FEATURE_HANDLERS, descriptor, feature_paths
from asset_files import write_asset


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    app = ROOT / "app"
    catalog = {}
    for feature in sorted(FEATURE_HANDLERS):
        path, handler = feature_paths(app, feature)
        data = descriptor(path, feature=feature)
        if not handler.is_file():
            raise ValueError(f"Missing Butter handler for {path.name}: {handler.name}.")
        data["editorHandler"] = handler.relative_to(app).as_posix()
        catalog[data["feature"]] = data
    text = ("// Generated by scripts/butter-catalog.py from first-party Butter command descriptors.\n"
            "globalThis.AtriumButterCatalog = " + json.dumps(catalog, ensure_ascii=True, separators=(",", ":")) + ";\n")
    target = app / "automation/command-catalog.js"
    if args.check:
        if target.read_text(encoding="utf-8") != text:
            parser.error("Run scripts/butter-catalog.py after editing Butter descriptors.")
    else:
        write_asset(target, text)


if __name__ == "__main__":
    main()
