#!/usr/bin/env python3
"""Project legacy MCP command policy to its demand-loaded worker dependency."""
import argparse
import json
from pathlib import Path
import sys

from asset_files import write_asset

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "app/automation/legacy-command-contract.js"
sys.path.insert(0, str(ROOT / "mcp"))
from commands import COMMANDS, allows_locked_revision


def render():
    unexpected = [name for name, spec in COMMANDS.items() if spec["kind"] not in {"read", "edit"}]
    if unexpected:
        raise ValueError("Unsupported legacy command kinds: " + ", ".join(sorted(unexpected)))
    read = json.dumps(sorted(name for name, spec in COMMANDS.items() if spec["kind"] == "read"))
    revision = json.dumps(sorted(name for name in COMMANDS if allows_locked_revision(name)))
    return (
        '"use strict";\n'
        "// Generated by scripts/legacy-command-catalog.py from mcp/commands.py.\n"
        "globalThis.AtriumLegacyCommandContract = Object.freeze({\n"
        f"  read: Object.freeze({read}),\n"
        f"  allowsLockedRevision: Object.freeze({revision})\n"
        "});\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_bytes() != text.encode("utf-8"):
            parser.error("The legacy command contract is missing or stale. Run python3 scripts/legacy-command-catalog.py.")
    else:
        write_asset(TARGET, text)


if __name__ == "__main__":
    main()
