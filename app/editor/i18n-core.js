"use strict";
// AtriumI18nCore: the full AtriumI18n (lazy; see docs/translating.md). The eager shim (i18n.js) keeps
// English free; this file replaces it when a module needs plurals or Intl formatting
// (AtriumLazy.need("AtriumI18nCore")) or a locale other than English is chosen. It takes over the
// shim's English definitions and scopes, then loads locales/en.js, locales/<id>.js and i18n-dom.js.
//   const t = AtriumI18n.define({"x.rows": "{count, plural, one {# row} other {# rows}}"}); t("x.rows", {count: 3})
//   AtriumI18n.text("Ready", "status")  number(n) unit(0.25, "mm") date(d, "short") ago(d)  setLocale("system"|id)
globalThis.AtriumI18nCore = (() => {
  const g = globalThis, doc = g.document, shim = g.AtriumI18n;
  // i18n-extract:available (generated by scripts/i18n-extract.py from app/locales/*.json; do not edit)
  const AVAILABLE = [{id:"en",name:"English",native:"English"},{id:"en-XA",name:"Pseudo-locale (testing)",native:"[Þšéûðö-ļöçåļé]",pseudo:true}];
  // i18n-extract:end
  const RTL = /^(ar|fa|he|iw|ur|ps|sd|ug|yi|dv)(-|$)/i;
  const english = Object.create(null), cats = Object.create(null), listeners = new Set(), warned = new Set(), cache = new Map();
  let active = "en", reverse = null, loading = Promise.resolve();
  let dev = false; try { dev = g.localStorage?.getItem("atrium.dev") === "1"; } catch {}
  const miss = k => { if (dev && !warned.has(active + k)) { warned.add(active + k); g.console?.warn?.("[i18n] " + active + " has no " + k); } };

  // A preference ("system", "en", "de"…) -> an available locale id.
  function resolve(pref) {
    if (pref && pref !== "system") return AVAILABLE.some(l => l.id === pref) ? pref : "en";
    const real = AVAILABLE.filter(l => !l.pseudo), nav = g.navigator;
    for (const tag of nav?.languages?.length ? nav.languages : [nav?.language || "en"]) {
      const t = String(tag).toLowerCase(), b = t.split("-")[0];
      const hit = real.find(l => l.id.toLowerCase() === t) || real.find(l => l.id.toLowerCase().split("-")[0] === b);
      if (hit) return hit.id;
    }
    return "en";
  }
  const pref = () => { try { return g.AtriumPref?.get?.("general.language", "system") || "system"; } catch { return "system"; } };

  // Messages: the locale's, else the module's English (define), else the extracted English.
  function t(key, p) {
    const c = cats[active];
    let m = c && key in c ? c[key] : (active !== "en" && miss(key), key in english ? english[key] : cats.en?.[key]);
    if (m == null) { miss(key); return key; }
    if (m.indexOf("{") < 0) return m;
    try { return format(m, p || {}); } catch (e) { miss(key + ": " + e.message); return m; }
  }
  function define(table) { for (const k in table) if (!(k in english)) english[k] = table[k]; return t; }
  // plural(3, "object"[, "objects"]) -> "3 objects" through the ICU message "plural.object"
  // ({count, plural, one {# object} other {# objects}}), so each locale's plural rules apply. Modules'
  // local plural()/count() helpers call this; scripts/i18n-extract.py harvests their literal words.
  function plural(n, one, many = one + "s") {
    const key = "plural." + (String(one).toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 48).replace(/_+$/, "") || "x");
    if (!(key in english)) english[key] = "{count, plural, one {# " + one + "} other {# " + many + "}}";
    return t(key, {count: n});
  }

  // ICU subset: {a}, {n, number[, integer|percent]}, {v, unit, mm}, {d, date[, short]}, {d, time},
  // {n, plural|selectordinal, =0 {…} one {…} other {…}} with #, {x, select, a {…} other {…}}.
  function end(s, i) { for (let d = 0, k = i; k < s.length; k++) if (s[k] === "{") d++; else if (s[k] === "}" && !--d) return k; throw Error("unbalanced braces"); }
  function format(s, p, hash) {
    let out = "";
    for (let i = 0; i < s.length; i++) {
      if (s[i] === "{") { const e = end(s, i); out += arg(s.slice(i + 1, e), p, hash); i = e; }
      else out += s[i] === "#" && hash !== undefined ? number(hash) : s[i];
    }
    return out;
  }
  function arg(body, p, hash) {
    const parts = body.split(","), v = p[parts[0].trim()], type = parts[1]?.trim(), style = parts.slice(2).join(",").trim();
    if (!type) return v == null ? "{" + parts[0].trim() + "}" : typeof v === "number" ? number(v) : String(v);
    if (/^(plural|selectordinal|select)$/.test(type)) {
      const o = {};
      for (let i = 0, b; (b = style.indexOf("{", i)) >= 0; i = end(style, b) + 1) o[style.slice(i, b).trim()] = style.slice(b + 1, end(style, b));
      if (type === "select") return format(o[String(v)] ?? o.other ?? "", p, hash);
      const n = Number(v) || 0, k = "=" + n in o ? "=" + n : intl("PluralRules", {type: type === "plural" ? "cardinal" : "ordinal"}).select(n);
      return format(o[k] ?? o.other ?? "", p, n);
    }
    if (type === "number") return number(v, style === "integer" ? {maximumFractionDigits: 0} : style === "percent" ? {style: "percent"} : undefined);
    if (type === "unit") return unit(v, style);
    if (type === "date" || type === "time") return date(v, type === "time" ? {timeStyle: style || "short"} : style || "medium");
    return String(v ?? "");
  }
  function intl(kind, o) {
    const id = active + kind + JSON.stringify(o || {});
    if (!cache.has(id)) { let f; try { f = new Intl[kind](active, o); } catch { f = new Intl[kind]("en", o); } cache.set(id, f); }
    return cache.get(id);
  }
  const number = (n, o) => (typeof Intl === "undefined" ? String(n) : intl("NumberFormat", o).format(n));
  const UNITS = {mm: "millimeter", cm: "centimeter", m: "meter", in: "inch", deg: "degree", "°": "degree", "%": "percent", s: "second",
    ms: "millisecond", min: "minute", h: "hour", KB: "kilobyte", MB: "megabyte", V: "volt", "°C": "celsius"};
  function unit(v, u, o) { // mil, oz, Ω… have no Intl unit: number + " " + unit
    try { if (UNITS[u]) return intl("NumberFormat", {style: "unit", unit: UNITS[u], maximumFractionDigits: 4, ...o}).format(v); } catch {}
    return number(Number(v), {maximumFractionDigits: 4, ...o}) + (u ? " " + u : "");
  }
  const date = (d, style) => intl("DateTimeFormat", typeof style === "object" ? style : {dateStyle: style || "medium"}).format(d instanceof Date ? d : new Date(d));
  function ago(when, now = Date.now()) {
    const s = Math.round((new Date(when) - now) / 1000), a = Math.abs(s);
    const [v, u] = a < 60 ? [s, "second"] : a < 3600 ? [Math.round(s / 60), "minute"] : a < 86400 ? [Math.round(s / 3600), "hour"] : [Math.round(s / 86400), "day"];
    return intl("RelativeTimeFormat", {numeric: "auto"}).format(v, u);
  }

  // Switching: load the English catalogue, the locale and i18n-dom.js as scripts (file:// safe).
  const script = src => new Promise((ok, no) => { const s = doc.createElement("script"); s.src = src; s.async = false; s.onload = ok; s.onerror = () => no(Error("Could not load " + src + ".")); doc.head.append(s); });
  async function setLocale(choice = pref()) {
    const id = resolve(choice), was = active;
    if (id === was && (id === "en" || cats[id])) return id;
    if (id !== "en" && doc?.head) {
      const files = [!cats.en && "locales/en.js", !cats[id] && "locales/" + id + ".js", !g.AtriumI18nDOM && "editor/i18n-dom.js"].filter(Boolean);
      try { await (loading = files.reduce((q, f) => q.then(() => script(f)), loading.catch(() => {}))); } catch (e) { g.AtriumNavHost?.info?.("Could not switch the language: " + e.message); throw e; }
    }
    if (id !== "en" && !cats[id]) { g.AtriumNavHost?.info?.("Could not switch the language: there are no messages for " + id + "."); throw Error("No messages for " + id + "."); }
    active = id; cache.clear();
    if (doc?.documentElement) { doc.documentElement.lang = id; doc.documentElement.dir = RTL.test(id) ? "rtl" : "ltr"; }
    g.AtriumI18nDOM?.apply(was, id);
    for (const fn of [...listeners]) try { fn(id, was); } catch (e) { g.console?.warn?.(e); }
    return id;
  }
  const scopes = shim?.scopes?.() || [];
  if (shim?.english) define(shim.english());
  const api = {t, define, plural, format: (m, p) => format(m, p || {}), number, unit, date, ago, resolve, setLocale,
    text: (s, ns) => (reverse && s ? reverse(s, ns) : s), // an English string as the locale shows it
    locale: () => active, dir: () => (RTL.test(active) ? "rtl" : "ltr"), get dev() { return dev; }, set dev(v) { dev = !!v; },
    available: () => AVAILABLE.map(l => ({...l})),
    add(id, messages) { cats[id] = {...cats[id], ...messages}; return id; }, // locales/<id>.js call this
    catalogue: id => cats[id] || null, english: () => ({...english}),
    onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); },
    // A module's DOM root and the en.json namespaces its text comes from (i18n-dom.js translates it).
    scope(selector, namespaces) { scopes.push({selector, namespaces: [].concat(namespaces || [])}); g.AtriumI18nDOM?.refresh(); },
    scopes: () => scopes.slice(), setReverse(fn) { reverse = fn; }};
  api.core = true;
  g.AtriumI18n = api;
  return api;
})();
