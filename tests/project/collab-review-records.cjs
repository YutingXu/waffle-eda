"use strict";
const assert = require("node:assert/strict");
for (const name of ["model","review-comments","collab-crdt"]) require(require("../support/app-source-paths.cjs").appFile(name+".js"));
const C=AtriumCollabCRDT, R=AtriumReviewComments, copy=Atrium.clone;
const source=Atrium.project("Review"); const sheet=source.documents[0].id;
const initial={doc:sheet,text:"Review",anchor:{kind:"point",at:[1,2]},author:"Reviewer",now:"2026-01-01"};
R.add(source,{...initial,id:"thread-a"}); R.add(source,{...initial,id:"thread-b"});
const create=(replica,p=source)=>C.create({replica,project:p});
const a=create("left"), b=create("right");
function edit(r,fn) {const p=copy(r.project());fn(p);return r.commit(p);}
function status(r,id){return R.thread(r.project(),id)?.status;}
const left=edit(a,p=>R.setStatus(p,"thread-a","resolved",{author:"Left",now:"2026-01-02"}));
const right=edit(b,p=>R.setStatus(p,"thread-b","resolved",{author:"Right",now:"2026-01-03"}));
assert.equal(left.ops.length,1);assert.ok(C.reviewOperation(left.ops[0]));assert.equal(left.ops[0].t,"set");
assert.ok(a.receive(right).touched.has("#meta"));b.receive(left);a.receive(right);
assert.equal(C.canon(a.project()),C.canon(b.project()));assert.equal(status(a,"thread-a"),"resolved");assert.equal(status(a,"thread-b"),"resolved");
b.receive(a.undo());assert.equal(status(b,"thread-a"),"open");assert.equal(status(b,"thread-b"),"resolved");
b.receive(a.redo());assert.equal(R.thread(b.project(),"thread-a").resolved.by,"Left");
const remove=edit(a,p=>R.remove(p,"thread-a"));
const reply=edit(b,p=>R.reply(p,"thread-b",{id:"reply-b",text:"Checked",now:"2026-01-04"}));
a.receive(reply);b.receive(remove);assert.equal(status(a,"thread-a"),undefined);assert.equal(R.thread(a.project(),"thread-b").replies.length,1);
b.receive(a.undo());assert.equal(status(b,"thread-a"),"resolved");assert.equal(R.thread(b.project(),"thread-b").replies[0].id,"reply-b");
const ra=edit(a,p=>R.reply(p,"thread-b",{id:"r-a",text:"First",now:"2026-01-05"}));
const rb=edit(b,p=>R.reply(p,"thread-b",{id:"r-b",text:"Second",now:"2026-01-05"}));
a.receive(rb);b.receive(ra);assert.deepEqual(R.thread(a.project(),"thread-b").replies.map(v=>v.id),["reply-b","r-a","r-b"]);
const offline=C.create({replica:"offline",snapshot:a.snapshot()});
const offlineChange=edit(offline,p=>R.setStatus(p,"thread-b","open"));
edit(a,p=>{p.review.records["thread-a"].text="Updated text";});
offline.merge(a.snapshot());a.receive(offlineChange);
assert.equal(C.canon(offline.project()),C.canon(a.project()));
assert.equal(status(offline,"thread-b"),"open");assert.equal(R.thread(offline.project(),"thread-a").text,"Updated text");
const legacy=create("legacy", {...source,review:undefined}).snapshot();delete legacy.reviewRecords;
legacy.meta.push(["review",{ts:{c:0,r:"~"},v:copy(source.review)}]);
const restored=C.create({replica:"upgraded",snapshot:legacy}); assert.deepEqual(restored.project().review,source.review);
const before=C.canon(a.project());assert.throws(()=>a.merge(legacy),/older editor/);
assert.throws(()=>a.receive({from:"old",ops:[{t:"meta",k:"review",ts:{c:2,r:"old"},n:1,v:source.review}]}),/older editor/);
assert.equal(C.canon(a.project()),before);
const deleting=create("deleting"),replying=create("replying");
const deleted=edit(deleting,p=>R.remove(p,"thread-a")),late=edit(replying,p=>R.reply(p,"thread-a",{id:"late",text:"During deletion",now:"2026-01-05"}));
deleting.receive(late);replying.receive(deleted);
assert.equal(R.thread(deleting.project(),"thread-a"),null);assert.equal(deleting.project().review.records.late.text,"During deletion");
replying.receive(deleting.undo());assert.deepEqual(R.thread(replying.project(),"thread-a").replies.map(r=>r.id),["late"]);
assert.equal(C.canon(replying.project()),C.canon(deleting.project()));
console.log("PASS two-peer independent resolutions, selective Undo and Redo, deletion, concurrent ordered replies, offline rejoin and legacy Review snapshots");
