"use strict";
const assert=require("node:assert/strict");
require("../../app/core/model.js");
require("../../app/library/parts.js");
require("../../app/schematic/blocks.js");
const A=Atrium, B=AtriumBlocks;
const project=AtriumParts.example(), board=project.documents[1];
const defs=new Map(project.library.map(d=>[d.id,d]));
const original=JSON.stringify(project);
const area=[[-1,-1],[37,23]];
const block=B.capture(board,defs,...area,"Analog channel");
assert.equal(block.items.length,board.items.length);
assert.deepEqual(B.capture(board,defs,area[1],area[0],block.name),block);
assert.equal(block.items.filter(i=>i.kind==="part").length,7);
assert.equal(block.library.length,5);
assert.deepEqual(block.size,[38,24]);
assert.equal(JSON.stringify(project),original);
const roundTrip=B.validate(JSON.parse(JSON.stringify(block)));
const first=B.prepare(project,roundTrip,[40,2]);
assert.equal(first.library.length,0,"reuse matching built-in definitions");
assert.equal(first.items.length,board.items.length);
const byKind=(items,kind)=>items.filter(i=>i.kind===kind);
assert.deepEqual(byKind(first.items,"track")[0].points[0],byKind(board.items,"track")[0].points[0].map((v,i)=>v+[41,3][i]));
assert.equal(first.nets.get("GND"),"B1/GND");
assert.ok(byKind(first.items,"part").every(i=>!board.items.some(old=>old.id===i.id||old.link===i.link||old.ref===i.ref)));
board.items.push(...first.items);
const second=B.prepare(project,block,[80,2],new Map([["GND","GND"]]));
assert.equal(second.nets.get("GND"),"GND");
assert.equal(second.nets.get("VDD"),"B2/VDD");
assert.ok(byKind(second.items,"part").every(i=>!board.items.some(old=>old.ref===i.ref)));
assert.throws(()=>B.prepare(project,block,[80,2],new Map([["VDD","missing"]]))); 
assert.throws(()=>B.prepare(project,block,[80,2],new Map([["GND","GND"],["VDD","GND"]])));
assert.throws(()=>B.capture(board,defs,[0,0],[0,0],"Empty"));
assert.throws(()=>B.capture(board,defs,[1000,1000],[1001,1001],"Empty"));
const inner=B.capture(board,defs,[7,8],[12,14],"Input R");
assert.ok(!inner.items.some(i=>i.kind==="track"),"cross-boundary traces must stay out");
assert.equal(inner.items.filter(i=>i.kind==="part").length,1);
const dest=A.project("Target"), pcb=dest.documents[1];
const sameId=A.clone(block.library[0]);sameId.name="Unrelated";dest.library.push(sameId);
const other=B.prepare(dest,block,[2,3]);
assert.equal(other.library.length,5);
dest.library.push(...other.library);pcb.items.push(...other.items);A.validate(dest);
assert.equal(B.prepare(dest,block,[100,100]).library.length,0);
const modified=A.clone(block);
modified.library[0].footprint.pads[0].net="EMBEDDED";
modified.library[0].footprint.shapes[0].net="EMBEDDED";
const emb=B.prepare(dest,modified,[4,5]);
assert.ok(emb.library[0].footprint.pads[0].net.endsWith("/EMBEDDED"));
assert.equal(emb.library[0].footprint.shapes[0].net,emb.library[0].footprint.pads[0].net);
assert.equal(modified.library[0].footprint.shapes[0].net,"EMBEDDED");
const bad=A.clone(block);bad.library=[];assert.throws(()=>B.validate(bad));
assert.throws(()=>B.validate({...block,version:2}));
console.log("Layout block tests passed: area selection, portable geometry, IDs, nets, reuse and import validation.");
