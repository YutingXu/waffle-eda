"use strict";
// Altium PCB classes beyond nets, pairs and xSignals (pcb-import.js boardClass): component classes become the
// board's component classes (component-classes.js), so InComponentClass rule scopes match their members.
// Altium's automatic placement classes keep their import-time members (approximated). A class Altium generated
// per schematic sheet that equals the class Waffle generates from that sheet is not stored twice. Superclasses
// (Altium's built-in "All ..." classes) are kept where Waffle knows the name, a loss where a rule names one
// Waffle does not know, and otherwise not applicable.
// Fixtures: synthetic ASCII PcbDoc and SchDoc built below.
const assert = require("node:assert/strict");
globalThis.CFB = require("../../app/vendor/cfb.min.js");
for (const name of ["obsolete-project","model","sch-objects","hierarchy","board-shape","board-shape-sources","net-intent","signals","altium-rules","pcb-draw","component-classes","query","rules","project-rules","pcb-pours","stackup",
  "pdf-fonts","altium-typefaces","altium-ids","source-file","sch-import","pcb-import","pcb-appearance","library-import-altium",
  "sexpr","import-kicad","import-eagle","sch-appearance","import-link","io","import-rules","translator-table","translator-registry","translator-provenance","translator-adapters","translators","parts","import-worker-client"]) require(require("../support/app-source-paths.cjs").appFile(name+".js"));
const T = AtriumTranslators, R = AtriumTranslatorRegistry, CC = AtriumComponentClasses;
const encoded = (name, text) => ({name, bytes: new TextEncoder().encode(text)});
const rule = (kind, name, scope, more) => "|RECORD=Rule|RULEKIND=" + kind + "|NAME=" + name + "|ENABLED=TRUE|PRIORITY=1|SCOPE1EXPRESSION=" + scope + "|SCOPE2EXPRESSION=All|" + more;
const component = (i, ref, x, src) => ["|RECORD=Component|ID=" + i + "|PATTERN=SOT23|SOURCEDESIGNATOR=" + ref + "|X=" + x + "mil|Y=500mil|ROTATION=0|LAYER=TOP|HEIGHT=200mil|UNIQUEID=COMP" + ref.padEnd(4, "X") + (src ? "|SOURCEUNIQUEID=\\" + src : ""),
  "|RECORD=Pad|COMPONENT=" + i + "|NAME=1|X=" + x + "mil|Y=500mil|XSIZE=20mil|YSIZE=20mil|SHAPE=RECTANGLE|LAYER=TOP|NET=0"];
const board = [
  "|RECORD=Board|VX0=0mil|VY0=0mil|VX1=2000mil|VY1=0mil|VX2=2000mil|VY2=2000mil|VX3=0mil|VY3=2000mil", "|RECORD=Net|ID=0|NAME=GND",
  ...component(0, "U1", 300, "SCHU1XXX"), ...component(1, "U2", 600, "SCHU2XXX"), ...component(2, "R1", 900, "SCHR1XXX"),
  rule("Height", "Drivers height", "InComponentClass('Drivers')", "MINHEIGHT=0mil|PREFHEIGHT=100mil|MAXHEIGHT=100mil"),
  rule("Height", "Top height", "InComponentClass('Top Side Components')", "MINHEIGHT=0mil|PREFHEIGHT=150mil|MAXHEIGHT=150mil").replace("PRIORITY=1", "PRIORITY=2"),
  rule("Height", "Any height", "InComponentClass('All Components')", "MINHEIGHT=0mil|PREFHEIGHT=300mil|MAXHEIGHT=300mil").replace("PRIORITY=1", "PRIORITY=3"),
  rule("Width", "Polygons", "InPolygonClass('All Polygons')", "MINLIMIT=5mil|PREFEREDWIDTH=6mil|MAXLIMIT=20mil|LAYERKIND=SameLayer"),
  "|RECORD=Class|NAME=All Nets|KIND=0|SUPERCLASS=TRUE",
  "|RECORD=Class|NAME=All Components|KIND=1|SUPERCLASS=TRUE",
  "|RECORD=Class|NAME=All Pads|KIND=3|SUPERCLASS=TRUE",
  "|RECORD=Class|NAME=All Polygons|KIND=7|SUPERCLASS=TRUE",
  "|RECORD=Class|NAME=Drivers|KIND=1|SUPERCLASS=FALSE|M0=U2|M1=U1|M2=U1",
  "|RECORD=Class|NAME=Top Side Components|KIND=1|SUPERCLASS=FALSE|AUTOGENERATEDCLASS=TRUE|M0=U1|M1=R1",
  "|RECORD=Class|NAME=Power|KIND=1|SUPERCLASS=FALSE|M0=R1",
  "|RECORD=Class|NAME=Logic|KIND=1|SUPERCLASS=FALSE|M0=U1",
  "|RECORD=Class|NAME=Testpads|KIND=3|SUPERCLASS=FALSE|M0=R1-1",
  "|RECORD=Class|NAME=Bad'name|KIND=1|SUPERCLASS=FALSE|M0=U1"].join("\r\n") + "\r\n";
// Sheets Power (R1) and Logic (U1, U2): Waffle generates a class per sheet from the linked parts.
function schDoc(parts) {
  const rows = ["|RECORD=31"];
  for (const [ref, uid] of parts) {
    const owner = rows.length;
    rows.push("|RECORD=1|LIBREFERENCE=PART|CURRENTPARTID=1|PARTCOUNT=2|LOCATION.X=100|LOCATION.Y=100|UNIQUEID=" + uid,
      "|RECORD=2|OWNERINDEX=" + owner + "|OWNERPARTID=1|PINCONGLOMERATE=0|PINLENGTH=20|LOCATION.X=90|LOCATION.Y=100|NAME=1|DESIGNATOR=1",
      "|RECORD=34|OWNERINDEX=" + owner + "|OWNERPARTID=-1|TEXT=" + ref + "|LOCATION.X=100|LOCATION.Y=120");
  }
  return "|HEADER=Protel for Windows - Schematic Capture Ascii File Version 5.0|WEIGHT=" + rows.length + "\r\n" + rows.join("\r\n") + "\r\n";
}
const files = [encoded("Board.PcbDoc", board), encoded("Power.SchDoc", schDoc([["R1", "SCHR1XXX"]])), encoded("Logic.SchDoc", schDoc([["U1", "SCHU1XXX"], ["U2", "SCHU2XXX"]]))];
const {model, report, provenance} = T.import(files, {source_rules: "use"});
Atrium.validate(model);
const pcb = model.documents.find(d => d.kind === "pcb");
const classRefs = [...R.references(report.kinds.find(r => r.kind === "Class"))];
const outcome = index => { const r = classRefs.find(x => x.source.object === "ASCII record#" + index); return [r.status, r.reason]; };
const at = name => board.split("\r\n").findIndex(l => l.includes("|NAME=" + name + "|") && l.startsWith("|RECORD=Class"));

// Stored component classes: a member list in natural order without repeats. "Power" equals the class Waffle
// generates from the Power sheet, so only the generated class remains; "Logic" differs from its sheet (U2).
assert.deepEqual(pcb.componentClasses, {Drivers: ["U1", "U2"], "Top Side Components": ["R1", "U1"], Logic: ["U1"]});
const classes = CC.list(pcb, model);
assert.deepEqual(classes.filter(c => c.name === "Power").map(c => [c.source, c.members]), [["sheet", ["R1"]]]);
assert.deepEqual(outcome(at("Drivers")), ["kept", "Stored as a component class of the board."]);
assert.deepEqual(outcome(at("Power")), ["kept", "Waffle generates this class, with the same members, from the schematic sheet of the same name."]);
assert.equal(outcome(at("Logic"))[0], "kept");
assert.deepEqual(outcome(at("Top Side Components")), ["approximated", "Altium updates this class from component placement. Waffle stores its members at import and does not update them."]);
assert.equal(outcome(at("Bad'name"))[0], "dropped");
assert.deepEqual(outcome(at("Testpads")), ["dropped", "Waffle has no pad classes."]);
// Superclasses.
assert.deepEqual(outcome(at("All Nets"))[0], "kept");
assert.match(outcome(at("All Components"))[1], /read All Components the same way/);
assert.deepEqual(outcome(at("All Pads")), ["notApplicable", "Altium's built-in class of every pad. It stores no members and no rule names it."]);
assert.deepEqual(outcome(at("All Polygons"))[0], "dropped", "a rule names a built-in class Waffle does not know");
assert.ok(!classRefs.some(r => /Unsupported class kind|Superclass membership/.test(r.reason || "")));
const classNotes = notes => notes.filter(n => /component class/.test(n));
const NOTES = ["Board.PcbDoc — Read 4 component classes. 1 of them follows component placement in Altium; Waffle keeps their members from the import.",
  "Board.PcbDoc — 1 of the component classes equals the class Waffle generates from the schematic sheet of the same name, so Waffle keeps that generated class instead of a stored copy. 3 component classes are stored."];
assert.deepEqual(classNotes(model.importNotes), NOTES, "the notes count the classes that remain");

// File › Open assembles results that crossed the worker boundary (structured clones): the same classes remain.
{
  const results = files.map(f => structuredClone(AtriumIO.read(f.name, f.bytes)));
  const opened = Atrium.validate(AtriumImport.assemble(results, files, Atrium.project("x", AtriumParts.catalogue), null).after);
  assert.deepEqual(opened.documents.find(d => d.kind === "pcb").componentClasses, pcb.componentClasses, "File › Open stores the same component classes");
  assert.deepEqual(classNotes(opened.importNotes), NOTES);
  // Adding a board to a project never folds the classes of a board the project already had.
  const before = structuredClone(opened), mine = before.documents.find(d => d.kind === "pcb");
  mine.componentClasses.Power = ["R1"];
  const extra = encoded("Extra.SchDoc", schDoc([["R9", "SCHR9XXX"]]));
  const added = AtriumImport.assemble([structuredClone(AtriumIO.read(extra.name, extra.bytes))], [extra], before, null, true);
  assert.deepEqual(added.after.documents.find(d => d.id === mine.id).componentClasses.Power, ["R1"]);
}

// The converted rules scope the imported classes: U1 and U2 are Drivers, R1 only on the top side, and the
// built-in All Components reaches whatever is left.
const height = ref => AtriumRules.query(pcb, "componentHeight", {kind: "part", component: ref}, {project: model})?.ruleName;
assert.deepEqual(["U1", "U2", "R1"].map(height), ["Drivers height", "Drivers height", "Top height"]);
const heights = provenance.sourceRules[0].report.filter(r => / height$/.test(r.name));
assert.deepEqual(heights.map(r => r.status), ["supported", "supported", "supported"]);
assert.ok(heights.every(r => !/class this board does not have/.test(r.reason || "")));
console.log("PASS Altium component classes, automatic classes, sheet classes and superclasses: " + Object.keys(pcb.componentClasses).length + " stored");
