"use strict";
const assert=require("node:assert/strict");
require("../../app/editor/labs.js");
require("../../app/editor/prefs.js");
const examples=__dirname+"/../../extensions/examples/", harness=require(examples+"harness.cjs");
async function run() {
  const h=await harness.setup(), X=h.X, prefs=globalThis.AtriumPrefs, labs=globalThis.AtriumLabs;
  let provider;
  globalThis.AtriumPalette={registerProvider(id,value){if (id==="extensions") provider=value;},invalidateProvider(){}};
  assert.equal(labs.notebookEnabled(),false);
  const ordinary={command:"mixed.regular",title:"Ordinary command"}, id="test.mixed-labs";
  const manifest={id,name:"Mixed notebook package",version:"1.0.0",apiVersion:1,main:"main.js",permissions:["ui:command"],
    contributes:{commands:[ordinary],paletteCommands:[{id:"lookup",name:"Notebook lookup",command:"mixed.lookup"}]}};
  const files={"waffle-extension.json":JSON.stringify(manifest),"main.js":'exports.activate=api=>{api.commands.register("mixed.regular",()=>"regular");api.commands.register("mixed.lookup",event=>{if(event.query==="hold until off"){console.log("notebook command running");return new Promise(()=>{});}return {kind:"detail",title:"Notebook details",text:"Ready"};});};'};
  await X.install(files);await h.installFolder(examples+"palette-footprints",["thumbnail.js"]);
  assert.equal(globalThis.AtriumExtensionNotebookHost,undefined);
  assert.equal(globalThis.AtriumExtensionPalette,undefined);
  assert.equal(globalThis.AtriumExtensionPaletteDeclarations,undefined);
  assert.ok(X.list().some(e=>e.id==="waffle.spice"),"the ordinary R3–5 extension is available");
  assert.equal(await X.execute(ordinary.command),"regular");
  await assert.rejects(X.activate("example.footprints"),/disabled/);
  await assert.rejects(X.execute("mixed.lookup"),/disabled/);
  const invalid={...manifest,id:"test.mixed-invalid",contributes:{commands:[{command:"invalid.regular",title:"Ordinary fallback"}],paletteCommands:[{id:"invalid",name:"Unknown command",command:"waffle.reserved"}]}};
  await X.install({"waffle-extension.json":JSON.stringify(invalid),"main.js":'exports.activate=api=>api.commands.register("invalid.regular",()=>"fallback");'});
  assert.equal(await X.execute("invalid.regular"),"fallback");
  prefs.set("labs.notebook",true);await X.readyNotebook();
  assert.ok(provider);
  const ctx={kind:"pcb",docId:h.board().id,point:[0,0],selection:[]};
  const keys=()=>provider.entries(ctx).map(r=>r.key);
  assert.ok(keys().includes("command:ext:test.mixed-labs:lookup"));
  assert.ok(keys().includes("insert:ext:example.footprints:footprint"));
  assert.ok(!keys().includes("command:ext:test.mixed-invalid:invalid"));
  assert.match(X.logs("test.mixed-invalid").map(e=>e.text).join(" "),/extension-owned command/);
  assert.equal(await X.execute("mixed.regular"),"regular");
  const ext="command:ext:test.mixed-labs:lookup", K=AtriumKeymap;
  K.setBindings(ext,["Ctrl+Alt+F9"]);const stored=K.exportJSON(), epoch=labs.notebookSignal();
  const active=provider.entries(ctx).find(row=>row.key===ext).run({query:"hold until off",context:ctx});
  for(let tries=0;tries<100 && !X.logs(id).some(line=>line.text==="notebook command running");tries++) await h.wait(5);
  assert.ok(X.logs(id).some(line=>line.text==="notebook command running"));
  prefs.set("labs.notebook",false);await active;
  assert.ok(!X.workers.some(w=>w.pool==="ext:"+id));
  assert.ok(epoch.aborted);assert.equal(K.resolve("Ctrl+Alt+F9",{kind:"pcb",canvas:true}),null);
  assert.equal(await X.execute("mixed.regular"),"regular");assert.deepEqual(keys(),[]);
  assert.equal(K.exportJSON(),stored);prefs.set("labs.notebook",true);await X.readyNotebook();
  assert.ok(keys().includes(ext));assert.equal(K.resolve("Ctrl+Alt+F9",{kind:"pcb",canvas:true}),ext);
  assert.equal(K.exportJSON(),stored);await X.shutdown();
  console.log("PASS parked and mixed extensions, real preference changes, validation, shortcut storage and ordinary SPICE");
}
run().catch(error=>{console.error(error);throw error;});
