"use strict";
const assert=require("node:assert/strict");
const vm=require("node:vm");
const source=require("node:fs").readFileSync(require("node:path").join(__dirname,"../bridge.js"),"utf8");
const crypto=require("node:crypto").webcrypto;

async function main() {
  const messages=[];
  const window={crypto,webkit:{messageHandlers:{atriumHost:{postMessage:s=>messages.push(JSON.parse(s))}}}};
  window.top=window;
  vm.runInNewContext(source,{window,File,Uint8Array,atob,btoa,AbortController,DOMException});
  const host=window.AtriumHost;
  const key="d".repeat(64);
  const row={name:"Board.kicad_pcb",data:"YQ==",importSaveKey:key,retainedInputToken:"private-input"};
  const done=(value,request=messages.at(-1))=>window.__atriumReceive(request.id,value);
  const choose=host.open();done([row]);
  const [file]=await choose;
  assert.equal(host.importSaveKey(file),key);
  assert.equal(messages.length,1);
  assert.equal(host.bindImportSave({file,files:[file]}),key);
  const bound=messages.at(-1);
  assert.equal(bound.action,"bindImportSave");
  assert.deepEqual(bound.tokens,["private-input"]);
  assert.equal(host.bindImportSave({file,files:[file]}),key);assert.equal(messages.at(-1),bound);
  assert.equal(file.path,undefined);
  const args={file,name:"Board",format:"kicad",labels:{title:"保存？",detail:"原始 KiCad 文件将保持不变。",save:"保存",cancel:"取消",export:"导出…"}};
  const out=host.importSaveChoice(args);assert.equal(messages.at(-1).session,bound.session);
  assert.deepEqual(messages.at(-1).labels,args.labels);done("export");assert.equal(await out,"export");
  const bytes=Uint8Array.of(1,2,255);const exported=host.writeImportExport({file,name:"Board",files:[{name:"nested/child.kicad_sch",bytes}]});
  assert.deepEqual(messages.at(-1).files,[{name:"nested/child.kicad_sch",data:"AQL/"}]);
  done({destination:"destination-grant",name:"Board"});assert.equal((await exported).name,"Board");
  const abort=new AbortController();const waiting=host.importSaveChoice({...args,signal:abort.signal});
  const original=messages.at(-1);abort.abort();assert.equal(messages.at(-1).action,"cancelImportSave");
  assert.equal(messages.at(-1).operation,original.operation);done("cancel",original);
  await assert.rejects(waiting,e=>e.name==="AbortError");
  const pending=host.importSaveChoice(args);const active=messages.at(-1);host.clearProjectPath();
  done("waffle",active);await assert.rejects(pending,e=>e.name==="AbortError");
  assert.throws(()=>host.rememberImportExport({file,destination:"destination-grant"}),/changed/);
  const id=crypto.randomUUID(), format="kicad";
  assert.ok(host.bindRestoredImportSave({id,sourceKey:key,format}));
  const recovery=host.importSaveChoice({id,sourceKey:key,name:"Draft",format,labels:args.labels});
  assert.equal(messages.at(-1).draftId,id);assert.equal(messages.at(-1).sourceToken,undefined);done("cancel");assert.equal(await recovery,"cancel");
  assert.throws(()=>host.writeImportExport({name:"Draft",bytes}),/changed/);
  assert.throws(()=>host.importSaveChoice({id,sourceKey:"9".repeat(64),format,labels:args.labels}),/changed/);
  const reused=host.reselectImportSave({sourceKey:key,format:"kicad"});done([row]);
  assert.equal(host.importSaveKey((await reused)[0]),key);
  const wrong=host.reselectImportSave({sourceKey:"9".repeat(64),format:"kicad"});done([row]);assert.equal(await wrong,null);
  const synthetic=new File(["x"],"Board.kicad_pcb");assert.equal(host.bindImportSave({file:synthetic}),null);
  console.log("PASS imported-file grants, choice, cancellation, complete output and exact draft reselect");
}
main().catch(error=>{console.error(error);process.exitCode=1;});
